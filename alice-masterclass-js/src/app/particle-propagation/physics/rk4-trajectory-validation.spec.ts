/**
 * Faza 15 — "Weryfikacja fizyki": compares our RK4 (through the exact
 * Chebyshev field map) against the `trajectory` arrays already stored in a
 * real `event_0_0.json` (produced by a different, helix-stepper-based
 * model). We do NOT expect point-for-point agreement — different
 * integration schemes, and the stored trajectory only approximates the
 * field as piecewise-constant — but both must agree on the things that are
 * determined by the physics itself: how far a track gets before leaving the
 * ~500 cm detector volume, and which way it bends for a given charge sign.
 */
import { TestBed } from '@angular/core/testing';
import { provideHttpClient } from '@angular/common/http';
import { HttpClient } from '@angular/common/http';
import { firstValueFrom } from 'rxjs';

import { MagneticFieldService } from './magnetic-field.service';
import { computeTrajectory } from './rk4-integrator';
import { PropagationParticle, Vec3 } from './propagation-types';
import { MAX_DETECTOR_R_CM } from './constants';

interface RawTrack {
  E: number;
  mass: number;
  px: number;
  py: number;
  pz: number;
  sign: number;
  trajectory: number[][] | null;
}

interface RawEvent {
  tracks: RawTrack[];
  decays: RawTrack[][];
}

function length(v: Vec3): number {
  return Math.hypot(v.x, v.y, v.z);
}

describe('RK4 vs. stored event trajectory (real field, real event_0_0.json)', () => {
  let magneticField: MagneticFieldService;
  let http: HttpClient;
  let rawEvent: RawEvent;

  beforeAll(async () => {
    TestBed.configureTestingModule({ providers: [provideHttpClient()] });
    magneticField = TestBed.inject(MagneticFieldService);
    http = TestBed.inject(HttpClient);
    await magneticField.load();
    rawEvent = await firstValueFrom(
      http.get<RawEvent>('assets/exercises/strangeness/part1/event_0_0.json')
    );
  }, 20000);

  it('finds at least one charged decay track with a stored trajectory', () => {
    const chargedDecays = rawEvent.decays.flat().filter((t) => t.sign !== 0 && t.trajectory && t.trajectory.length > 1);
    expect(chargedDecays.length).toBeGreaterThan(0);
  });

  it('reaches a comparable radial extent and bends the same way as the stored trajectory, for every charged decay track', () => {
    const chargedDecays = rawEvent.decays.flat().filter((t) => t.sign !== 0 && t.trajectory && t.trajectory.length > 1);
    expect(chargedDecays.length).toBeGreaterThan(0);

    for (const raw of chargedDecays) {
      const trajectory = raw.trajectory!;
      const vertex: Vec3 = { x: trajectory[0][0], y: trajectory[0][1], z: trajectory[0][2] };
      const momentum: Vec3 = { x: raw.px, y: raw.py, z: raw.pz };
      const particle: PropagationParticle = {
        id: 'validation',
        origin: 'v0',
        vertex,
        momentum,
        charge: raw.sign,
        mass: raw.mass,
        energy: raw.E,
      };

      const track = computeTrajectory(particle, (pos) => magneticField.field(pos));
      expect(track.pointCount).toBeGreaterThan(1);

      // 1) Both models should let the particle travel roughly out to the
      // detector's outer radius (allowing generous slack: the reference
      // trajectory was generated by a different stepper/field truncation).
      const storedLast = trajectory[trajectory.length - 1];
      const storedFinalR = Math.hypot(storedLast[0], storedLast[1], storedLast[2]);
      const rk4FinalR = Math.hypot(
        track.positions[(track.pointCount - 1) * 3],
        track.positions[(track.pointCount - 1) * 3 + 1],
        track.positions[(track.pointCount - 1) * 3 + 2]
      );
      expect(storedFinalR).toBeGreaterThan(MAX_DETECTOR_R_CM * 0.5);
      expect(rk4FinalR).toBeGreaterThan(MAX_DETECTOR_R_CM * 0.5);
      expect(rk4FinalR).toBeLessThan(MAX_DETECTOR_R_CM * 1.1);

      // 2) Same sense of curvature: project the stored trajectory's net
      // deflection (final tangent direction vs. initial momentum direction)
      // and compare its sign against RK4's, via the cross product with the
      // local field direction at the vertex (B is ~solenoidal/along z near
      // the vertex for most of these low-|z| decay vertices).
      const p0 = { x: raw.px, y: raw.py, z: raw.pz };
      const p0n = length(p0) > 0 ? { x: p0.x / length(p0), y: p0.y / length(p0), z: p0.z / length(p0) } : p0;

      // Compare over the same physical arc length near the vertex — the
      // stored trajectory's point spacing (~14 cm here) is much coarser
      // than RK4's fixed 1.5 cm step, so "same index" would compare wildly
      // different arc lengths and any tiny local difference would compound
      // into a meaningless divergence hundreds of cm into a ~250 cm-radius
      // helix.
      const storedLocalIdx = Math.min(3, trajectory.length - 1);
      const storedArcLength =
        storedLocalIdx *
        Math.hypot(
          trajectory[1][0] - trajectory[0][0],
          trajectory[1][1] - trajectory[0][1],
          trajectory[1][2] - trajectory[0][2]
        );
      const storedDir: Vec3 = {
        x: trajectory[storedLocalIdx][0] - trajectory[0][0],
        y: trajectory[storedLocalIdx][1] - trajectory[0][1],
        z: trajectory[storedLocalIdx][2] - trajectory[0][2],
      };

      const rk4StepCm = 1.5;
      const rk4LocalIdx = Math.min(Math.round(storedArcLength / rk4StepCm), track.pointCount - 1);
      const rk4Dir: Vec3 = {
        x: track.positions[rk4LocalIdx * 3] - track.positions[0],
        y: track.positions[rk4LocalIdx * 3 + 1] - track.positions[1],
        z: track.positions[rk4LocalIdx * 3 + 2] - track.positions[2],
      };

      // Over this short, matched arc length the two models should agree
      // closely, not just in sign: same starting vertex/momentum/charge,
      // (near-)identical field, same physics. `storedDir`/`rk4Dir` should
      // point in essentially the same direction — deflection from the
      // straight-line direction (the "which way does it bend" question) is
      // checked via the sign of the dot product of their components
      // perpendicular to the initial momentum, and additionally the full
      // vectors must be within a tight angle of each other.
      const perp = (dir: Vec3): Vec3 => {
        const along = dir.x * p0n.x + dir.y * p0n.y + dir.z * p0n.z;
        return { x: dir.x - along * p0n.x, y: dir.y - along * p0n.y, z: dir.z - along * p0n.z };
      };
      const storedPerp = perp(storedDir);
      const rk4Perp = perp(rk4Dir);
      const agreement = storedPerp.x * rk4Perp.x + storedPerp.y * rk4Perp.y + storedPerp.z * rk4Perp.z;
      expect(agreement).toBeGreaterThan(0);

      const cosAngle =
        (storedDir.x * rk4Dir.x + storedDir.y * rk4Dir.y + storedDir.z * rk4Dir.z) /
        (length(storedDir) * length(rk4Dir));
      expect(cosAngle).toBeGreaterThan(0.98); // within ~11 degrees
    }
  }, 20000);
});
