def render(block: dict, indent: int) -> str:
    """Serialises the block with the two-space style the i18n files already use."""
    body = json.dumps(block, ensure_ascii=False, indent=2)
    pad = " " * indent
    return "\n".join(pad + line if line else line for line in body.splitlines()).lstrip()


def main() -> None:
    for language, block in BLOCKS.items():
        path = I18N_DIR / f"{language}.json"
        text = path.read_text(encoding="utf-8")

        existing = json.loads(text)
        if "JPSI" in existing:
            print(f"{language}: JPSI already present, skipping")
            continue

        closing = text.rstrip().rfind("}")
        head = text[:closing].rstrip()
        # head currently ends with the previous top-level block's closing brace.
        merged = f'{head},\n  "JPSI": {render(block, 2)}\n}}\n'

        json.loads(merged)  # fail loudly rather than write a broken file
        path.write_text(merged, encoding="utf-8")
        print(f"{language}: JPSI block added")


if __name__ == "__main__":
    main()
